public enum ColorSelection {
    /// §3.5: (rule hash + quip sequence) mod 6, bumped once if a bubble on screen already uses that group.
    public static func groupIndex(ruleHash: UInt64, quipSequence: Int, occupied: Set<Int>) -> Int {
        let index = Int((ruleHash &+ UInt64(quipSequence)) % 6)
        return occupied.contains(index) ? (index + 1) % 6 : index
    }

    /// §3.4: golden-angle hue walk from the per-launch base hue.
    public static func randomGroup(baseHue: Double, index: Int) -> ColorGroup {
        let hue = (baseHue + Double(index) * 137.5).truncatingRemainder(dividingBy: 360)
        return ColorGroup(
            fill: PaletteColor(hue: hue, saturation: 0.35, brightness: 1.0),
            text: PaletteColor(hue: hue, saturation: 0.80, brightness: 0.38),
            stroke: PaletteColor(hue: hue, saturation: 0.55, brightness: 0.85))
    }
}
